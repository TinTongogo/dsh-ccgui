interface MarkProps {
  readonly id: ProviderMarkId
  readonly size: number
}

function svgProps({ id, size }: MarkProps, viewBox: string) {
  return {
    width: size,
    height: size,
    viewBox,
    'aria-hidden': true,
    'data-cli-mark': id,
    style: { flex: 'none' },
  } as const
}

/** The gradient id is per instance: several OMP marks on one page must not share one. */
function OmpMark(props: MarkProps) {
  const gradient = useId().replace(/:/g, '')
  return (
    <svg {...svgProps(props, '0 0 64 64')}>
      <defs>
        <linearGradient id={gradient} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="oklch(0.7 0.24 340)" />
          <stop offset=".5" stopColor="oklch(0.62 0.21 295)" />
          <stop offset="1" stopColor="oklch(0.81 0.14 200)" />
        </linearGradient>
      </defs>
      <path fill={`url(#${gradient})`} d={OMP_PATH} />
    </svg>
  )
}

/** The gradient id is per instance, for the same reason as OMP's. */
function CodeBuddyMark(props: MarkProps) {
  const gradient = useId().replace(/:/g, '')
  return (
    <svg {...svgProps(props, '0 0 24 24')}>
      <defs>
        <radialGradient
          id={gradient}
          cx="0"
          cy="0"
          r="1"
          gradientUnits="userSpaceOnUse"
          gradientTransform="matrix(-9.00009 -16 16 -9.00009 21 24.5)"
        >
          <stop stopColor="#2EA99D" />
          <stop offset="1" stopColor="#6C4DFF" />
        </radialGradient>
      </defs>
      <path fill={`url(#${gradient})`} d={CODEBUDDY_BACKGROUND_PATH} />
      {CODEBUDDY_FACE_PATHS.map((path) => (
        <path key={path} fill="#fff" d={path} />
      ))}
    </svg>
  )
}

function ColoredMark(props: MarkProps & { readonly path: string; readonly color: string }) {
  return (
    <svg {...svgProps(props, '0 0 24 24')}>
      <path fill={props.color} d={props.path} />
    </svg>
  )
}

function MonochromeMark(props: MarkProps & { readonly paths: readonly string[] }) {
  return (
    <svg {...svgProps(props, '0 0 24 24')} fill="currentColor" fillRule="evenodd">
      {props.paths.map((path) => (
        <path key={path} d={path} />
      ))}
    </svg>
  )
}

/** A plain prompt, for a CLI with no mark of its own. */
function GenericCliMark(props: MarkProps) {
  return (
    <svg
      {...svgProps(props, '0 0 24 24')}
      fill="none"
      stroke="currentColor"
      strokeWidth="2.2"
      strokeLinecap="round"
      strokeLinejoin="round"
    >
      <path d="M4 7l6 5-6 5" />
      <path d="M12 19h8" />
    </svg>
  )
}

/**
 * Draw a provider's mark.
 * @param props.provider - a provider route.
 * @param props.size - width and height in pixels.
 * @returns the mark, or nothing for a provider with none.
 */
export function ProviderMark({
  provider,
  size,
}: {
  readonly provider: string
  readonly size: number
}): ReactElement | null {
  const id = markOf(provider)
  if (id === undefined) return null
  if (id === 'omp') return <OmpMark id={id} size={size} />
  if (id === 'codebuddy') return <CodeBuddyMark id={id} size={size} />
  const colored = COLORED[id]
  if (colored !== undefined) return <ColoredMark id={id} size={size} {...colored} />
  const paths = MONOCHROME[id]
  if (paths !== undefined) return <MonochromeMark id={id} size={size} paths={paths} />
  return <GenericCliMark id={id} size={size} />
}
